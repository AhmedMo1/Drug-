export function findAdultMonograph(drug: Drug): AdultDrugMonograph | null {
  if (!drug) return null;

  const textToMatch = `${drug.scientific_name} ${drug.commercial_name_en} ${drug.commercial_name_ar || ''} ${drug.drug_class || ''}`.toUpperCase();

  for (const mono of ADULT_DRUG_MONOGRAPHS) {
    const isMatch = mono.activeIngredientKeywords.some(keyword => textToMatch.includes(keyword));
    if (isMatch) return mono;
  }

  return null;
}
